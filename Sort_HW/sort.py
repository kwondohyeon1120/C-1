# 4. 셸 정렬 (크누스 수열)
# ==========================================
def shell_sort_knuth(arr):
    a = list(arr)
    n = len(a)
    comparisons = 0
    moves = 0

    start_time = time.perf_counter()
    gap = 1
    while gap < n // 3:
        gap = 3 * gap + 1

    while gap >= 1:
        for i in range(gap, n):
            key = a[i]
            moves += 1
            j = i - gap
            while j >= 0:
                comparisons += 1
                if a[j] > key:
                    a[j + gap] = a[j]
                    moves += 1
                    j -= gap
                else:
                    break
            a[j + gap] = key
            moves += 1
        gap = (gap - 1) // 3

    elapsed = time.perf_counter() - start_time
    return comparisons, moves, elapsed

