# 3. 셸 정렬 (기본 - 절반 축소)
# ==========================================
def shell_sort(arr):
    a = list(arr)
    n = len(a)
    comparisons = 0
    moves = 0

    start_time = time.perf_counter()
    gap = n // 2
    while gap >= 1:
        for i in range(gap, n):
            key = a[i]
            moves += 1
            j = i - gap
            while j >= 0:
                comparisons += 1
                if a[j] > key:
                    a[j + gap] = a[j]
                    moves += 1
                    j -= gap
                else:
                    break
            a[j + gap] = key
            moves += 1
        gap //= 2

    elapsed = time.perf_counter() - start_time
    return comparisons, moves, elapsed


